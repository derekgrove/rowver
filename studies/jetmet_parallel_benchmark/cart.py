try:
    FILE_COUNT = int(os.environ.get("ROWVER_JETMET_FILES", "4"))
except ValueError as exc:
    raise CartError("ROWVER_JETMET_FILES must be one of 4, 8, 16, 32, 64, 128") from exc
if FILE_COUNT not in SIZES:
    raise CartError("ROWVER_JETMET_FILES must be one of 4, 8, 16, 32, 64, 128")


def KEEP(events):
    return (events.nJet >= 1) & (events.MET_pt > 1000.0)


CART = Cart(
    fileset={
        "JetMET 2018 DATA": {
            "files": {f"{CMS}{path}": "Events" for path in FILES[:FILE_COUNT]},
            "metadata": {"kind": "data", "weights": None},
        },
    },
    keep=KEEP,
    columns={"MET": "MET_pt", "Njet": "nJet"},
    title=f"JetMET parallel benchmark ({FILE_COUNT} files)",
    note="Remote-I/O benchmark; MET > 1000 GeV keeps the cartridge small.",
)
